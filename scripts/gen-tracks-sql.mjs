// Writes supabase/tracks.sql from the content files, so the database knows
// how many challenges each certificate requires. Re-run after editing content.
import { writeFileSync } from 'node:fs'
import { tracks } from '../src/content/index.js'

const rows = tracks.map((t) => `  ('${t.id}', '${t.title.replace(/'/g, "''")}', ${t.challenges.length})`).join(',\n')
const sql = `-- Generated by \`npm run tracks-sql\`. Run in Supabase > SQL Editor after schema.sql,
-- and again whenever you add or remove challenges.
insert into public.tracks (id, title, challenge_count) values
${rows}
on conflict (id) do update set title = excluded.title, challenge_count = excluded.challenge_count;
`
writeFileSync(new URL('../supabase/tracks.sql', import.meta.url), sql)
console.log(sql)
